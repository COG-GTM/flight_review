#!/usr/bin/env bash
# Renders the Helm chart to plain manifests under deploy/k8s/rendered/ so a
# site without Helm (or an assessor) can review/apply exactly what the chart
# produces. Re-run after any chart or values change and commit the result.
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CHART="$REPO_ROOT/deploy/helm/flight-review"
OUT="$REPO_ROOT/deploy/k8s/rendered"
RELEASE="${RELEASE:-flight-review}"
NAMESPACE="${NAMESPACE:-flight-review}"
VALUES="${VALUES:-$CHART/values.yaml}"

command -v helm >/dev/null || { echo "helm is required" >&2; exit 1; }
mkdir -p "$OUT"
rm -f "$OUT"/*.yaml
helm template "$RELEASE" "$CHART" \
    --namespace "$NAMESPACE" \
    --values "$VALUES" \
    --output-dir "$OUT/.tmp" >/dev/null
# flatten helm's <chart>/templates/<file> layout
# tests/ (helm test hook) and the config Secret (site-specific, holds the SMTP
# password / API keys) are deliberately not rendered to the repo.
find "$OUT/.tmp" -name '*.yaml' -not -path '*/tests/*' -not -name 'secret-config.yaml' -exec sh -c 'mv "$1" "$2/$(basename "$1")"' _ {} "$OUT" \;
rm -rf "$OUT/.tmp"
{
  echo "# Generated by deploy/scripts/render.sh from $(git -C "$REPO_ROOT" rev-parse --short HEAD) — do not edit."
  echo "# Apply order: deploy/k8s/00-03*.yaml, then the config Secret (helm or kubectl create secret generic flight-review-config --from-file=config_user.ini), then these files."
  echo "# helm $(helm version --short) | chart $(grep '^version:' "$CHART/Chart.yaml" | awk '{print $2}') | values $(basename "$VALUES")"
} > "$OUT/README.md"
ls -1 "$OUT"
